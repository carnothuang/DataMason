/** M8-3 纯手动专业建库工作台（SQL + 可视化，同一份草稿）。
 *
 * 草稿单一数据源（DR-44）：SQL 经后端解析写回 HybridDraft，可视化直接改草稿，
 * 反生成 SQL 由草稿确定性序列化；不调 LLM、不执行用户 DDL（DR-42）。
 * 宽屏左右分栏、窄屏 Segmented 切换（Q1）；默认不带演示种子（Q2）；
 * 仅创建模式可用，直连无入口（DR-45）。最终 spec_json 复用 confirm 落库。
 */
import { useEffect, useReducer, useState } from "react";
import {
  Alert,
  App,
  Button,
  Checkbox,
  Form,
  Input,
  Segmented,
  Select,
  Space,
  Tag,
  Typography,
} from "antd";
import {
  Connection,
  DeployApi,
  DeployResult,
  ManualDialect,
  ManualSchemaSpec,
  ManualApi,
} from "../../api";
import ErCanvas from "../../components/ErCanvas";
import MaximizableModal from "../../components/MaximizableModal";
import {
  HybridDraft,
  hybridReducer,
  normalizeColumn,
} from "./hybridDraft";

const { Text } = Typography;

const EMPTY_DRAFT: HybridDraft = { biz_notes: "", tables: [] };

const DIALECT_OPTIONS = [
  { value: "sqlite", label: "SQLite" },
  { value: "mysql", label: "MySQL" },
  { value: "postgresql", label: "PostgreSQL" },
];

const EXAMPLE_SQL: Record<ManualDialect, string> = {
  sqlite: `CREATE TABLE customers (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(30) UNIQUE
);

CREATE TABLE orders (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  customer_id INTEGER REFERENCES customers(id),
  amount DECIMAL(10,2) NOT NULL
);`,
  mysql: `CREATE TABLE customers (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(30) UNIQUE
);

CREATE TABLE orders (
  id INTEGER PRIMARY KEY AUTO_INCREMENT,
  customer_id INTEGER REFERENCES customers(id),
  amount DECIMAL(10,2) NOT NULL
);`,
  postgresql: `CREATE TABLE customers (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name VARCHAR(100) NOT NULL,
  phone VARCHAR(30) UNIQUE
);

CREATE TABLE orders (
  id INTEGER PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  customer_id INTEGER REFERENCES customers(id),
  amount DECIMAL(10,2) NOT NULL
);`,
};

interface ParseIssue {
  table?: string | null;
  column?: string | null;
  message: string;
}

interface Props {
  open: boolean;
  conns: Connection[];
  onClose: () => void;
  onDeployed: (result: DeployResult) => void;
}

/** 整数主键是否承载自增（与 ddl_builder 门控一致：仅 INTEGER/BIGINT 主键自增）。 */
function isAutoincPk(c: { is_pk: boolean; type: string }): boolean {
  return c.is_pk && (c.type === "INTEGER" || c.type === "BIGINT");
}

/** 草稿 → 提交用 SchemaSpec（剥离前端稳定 key，不携带归属列）。 */
function draftToSpec(draft: HybridDraft): ManualSchemaSpec {
  return {
    biz_notes: draft.biz_notes,
    tables: draft.tables.map((t) => ({
      name: t.name,
      biz_name: t.biz_name,
      biz_notes: t.biz_notes,
      columns: t.columns.map((c) => ({
        name: c.name,
        biz_name: c.biz_name,
        type: c.type,
        length: c.length,
        nullable: c.nullable,
        unique: c.unique,
        is_pk: c.is_pk,
        autoincrement: isAutoincPk(c),
        is_fk: c.is_fk,
        ref_table: c.ref_table,
        ref_column: c.ref_column,
      })),
    })),
  };
}

function qIdent(name: string, dialect: ManualDialect): string {
  if (dialect === "mysql") return `\`${name}\``;
  if (dialect === "postgresql") return `"${name}"`;
  return name;
}

function colTypeSql(col: { type: string; length: number | null }, dialect: ManualDialect): string {
  switch (col.type) {
    case "INTEGER":
      return "INTEGER";
    case "BIGINT":
      return "BIGINT";
    case "VARCHAR":
      return `VARCHAR(${col.length ?? 255})`;
    case "TEXT":
      return "TEXT";
    case "BOOLEAN":
      return dialect === "mysql" ? "TINYINT(1)" : dialect === "postgresql" ? "BOOLEAN" : "INTEGER";
    case "DATETIME":
      return dialect === "postgresql" ? "TIMESTAMP" : "DATETIME";
    case "DECIMAL":
      return "DECIMAL(18,2)";
    case "FILE":
      return `VARCHAR(${col.length ?? 255})`;
    default:
      return col.type;
  }
}

/** 草稿 → 目标方言 CREATE TABLE（与 ddl_builder 渲染口径一致，DR-44 单一真相）。 */
function draftToSql(draft: HybridDraft, dialect: ManualDialect): string {
  return draft.tables
    .map((t) => {
      const lines = t.columns.map((c) => {
        const autoinc = isAutoincPk(c);
        const parts: string[] = [qIdent(c.name, dialect)];
        if (dialect === "postgresql" && autoinc) {
          parts.push(
            c.type === "BIGINT"
              ? "BIGINT GENERATED BY DEFAULT AS IDENTITY"
              : "INTEGER GENERATED BY DEFAULT AS IDENTITY",
          );
        } else {
          parts.push(colTypeSql(c, dialect));
        }
        if (c.is_pk) {
          parts.push("PRIMARY KEY");
          if (autoinc && dialect === "sqlite") parts.push("AUTOINCREMENT");
          if (autoinc && dialect === "mysql") parts.push("AUTO_INCREMENT");
        }
        if (!c.nullable && !c.is_pk) parts.push("NOT NULL");
        if (c.unique && !c.is_pk) parts.push("UNIQUE");
        if (c.is_fk && c.ref_table && c.ref_column) {
          parts.push(`REFERENCES ${qIdent(c.ref_table, dialect)}(${qIdent(c.ref_column, dialect)})`);
        }
        return `  ${parts.join(" ")}`;
      });
      return `CREATE TABLE ${qIdent(t.name, dialect)} (\n${lines.join(",\n")}\n);`;
    })
    .join("\n\n");
}

export default function ManualBuilder({ open, conns, onClose, onDeployed }: Props) {
  const { message, modal } = App.useApp();
  const [form] = Form.useForm<{ biz_name: string; description: string; seed: boolean }>();
  const [draft, dispatch] = useReducer(hybridReducer, EMPTY_DRAFT);
  const [dialect, setDialect] = useState<ManualDialect>("sqlite");
  const [targetConnId, setTargetConnId] = useState<number>();
  const [sql, setSql] = useState("");
  const [issues, setIssues] = useState<ParseIssue[]>([]);
  const [loading, setLoading] = useState(false);
  const [wide, setWide] = useState(() => window.innerWidth >= 1280);
  const [pane, setPane] = useState<"sql" | "visual">("sql");
  const [selected, setSelected] = useState<string | null>(null);
  const [layout, setLayout] = useState<"ring" | "grid">("ring");

  useEffect(() => {
    const onResize = () => setWide(window.innerWidth >= 1280);
    window.addEventListener("resize", onResize);
    return () => window.removeEventListener("resize", onResize);
  }, []);

  useEffect(() => {
    if (!open || draft.tables.length === 0) return;
    const beforeUnload = (e: BeforeUnloadEvent) => {
      e.preventDefault();
      e.returnValue = "";
    };
    window.addEventListener("beforeunload", beforeUnload);
    return () => window.removeEventListener("beforeunload", beforeUnload);
  }, [open, draft.tables.length]);

  const resetAll = () => {
    form.resetFields();
    form.setFieldsValue({ seed: false });
    dispatch({ type: "reset", draft: EMPTY_DRAFT });
    setDialect("sqlite");
    setTargetConnId(undefined);
    setSql("");
    setIssues([]);
    setPane("sql");
    setSelected(null);
  };

  const close = () => {
    if (draft.tables.length) {
      modal.confirm({
        title: "放弃当前草稿？",
        content: "专业建库草稿只保存在浏览器内存，关闭后本次设计将丢失。",
        okText: "放弃草稿",
        okButtonProps: { danger: true },
        cancelText: "继续编辑",
        onOk: () => {
          resetAll();
          onClose();
        },
      });
      return;
    }
    resetAll();
    onClose();
  };

  // 选择落库位置时联动方言（MySQL/PG 服务器连接决定解析口径）
  const onTargetChange = (v: number | undefined) => {
    setTargetConnId(v);
    if (v) {
      const conn = conns.find((c) => c.id === v);
      if (conn && (conn.dialect === "mysql" || conn.dialect === "postgresql")) {
        setDialect(conn.dialect);
      }
    }
  };

  const onDialectChange = (v: ManualDialect) => {
    setDialect(v);
    setIssues([]);
  };

  const parseSql = async () => {
    if (!sql.trim()) {
      message.error("请先书写 CREATE TABLE 建表语句");
      return;
    }
    setLoading(true);
    setIssues([]);
    try {
      const r = await ManualApi.parseSql({
        sql,
        dialect,
        mode: "create",
        target_connection_id: targetConnId,
      });
      const spec = r.spec_json;
      const mapped: HybridDraft = {
        biz_notes: spec.biz_notes ?? "",
        tables: spec.tables.map((t) => ({
          name: t.name,
          biz_name: t.biz_name ?? "",
          biz_notes: t.biz_notes ?? "",
          columns: (t.columns || []).map((c) => normalizeColumn({ ...c })),
        })),
      };
      dispatch({ type: "reset", draft: mapped });
      setSelected(mapped.tables[0]?.name ?? null);
      message.success(`已解析 ${r.table_count} 张表，结构已同步到可视化形态`);
    } catch (e) {
      const err = e as Error & { errors?: ParseIssue[] };
      setIssues(err.errors ?? [{ message: err.message }]);
      message.error(err.message);
    } finally {
      setLoading(false);
    }
  };

  // 可视化改动 → 反生成 SQL：SQL 不保留手写注释/排版，切换前提示（R2/DR-44）
  const regenerateSql = () => {
    modal.confirm({
      title: "按当前结构重排 SQL？",
      content: "将用可视化草稿重新生成 CREATE TABLE，手写注释与排版不会保留。",
      okText: "重排 SQL",
      cancelText: "取消",
      onOk: () => {
        setSql(draftToSql(draft, dialect));
        setIssues([]);
        if (!wide) setPane("sql");
        message.success("已按草稿重新生成 SQL");
      },
    });
  };

  const deploy = async () => {
    const values = await form.validateFields();
    if (draft.tables.length === 0) {
      message.error("草稿还没有表，请先写 SQL 解析或在可视化形态加表");
      return;
    }
    setLoading(true);
    setIssues([]);
    try {
      const result = await DeployApi.confirm({
        spec_json: draftToSpec(draft) as unknown as Record<string, unknown>,
        biz_name: values.biz_name,
        description: values.description,
        seed_data: values.seed,
        mode: "create",
        target_connection_id: targetConnId,
      });
      resetAll();
      onDeployed(result);
    } catch (e) {
      const err = e as Error & { errors?: ParseIssue[] };
      setIssues(err.errors ?? [{ message: err.message }]);
      message.error(err.message);
    } finally {
      setLoading(false);
    }
  };

  const sqlPane = (
    <div style={{ display: wide || pane === "sql" ? "flex" : "none", flexDirection: "column", flex: 1, minWidth: 0 }}>
      <Space style={{ marginBottom: 8 }} wrap>
        <Button size="small" onClick={() => setSql(EXAMPLE_SQL[dialect])}>载入示例</Button>
        <Button size="small" onClick={() => setSql("")}>清空</Button>
        <Text type="secondary" style={{ fontSize: 12 }}>
          仅支持 CREATE TABLE；点「解析为结构」同步到右侧草稿
        </Text>
      </Space>
      <Input.TextArea
        value={sql}
        onChange={(e) => setSql(e.target.value)}
        spellCheck={false}
        rows={wide ? 22 : 12}
        placeholder={EXAMPLE_SQL[dialect]}
        style={{ fontFamily: "var(--fn-font-mono, monospace)", fontSize: 12 }}
      />
      <Space style={{ marginTop: 8 }}>
        <Button type="primary" loading={loading} onClick={parseSql}>解析为结构</Button>
      </Space>
    </div>
  );

  const visualPane = (
    <div style={{ display: wide || pane === "visual" ? "block" : "none", flex: 1, minWidth: 0 }}>
      <Space style={{ marginBottom: 8 }} wrap>
        <Button size="small" onClick={regenerateSql} disabled={draft.tables.length === 0}>按结构生成 SQL</Button>
        <Text type="secondary" style={{ fontSize: 12 }}>
          增删表/字段、连线外键；FILE 附件列只在此形态标记
        </Text>
      </Space>
      <ErCanvas
        manual
        draft={draft}
        dispatch={dispatch}
        selected={selected}
        onSelect={setSelected}
        width={wide ? 520 : 860}
        height={wide ? 420 : 460}
        layout={layout}
        onLayoutChange={setLayout}
      />
    </div>
  );

  return (
    <MaximizableModal
      title="纯手动建库 · 专业模式（SQL + 可视化）"
      open={open}
      onCancel={close}
      width={1280}
      footer={
        <Space>
          <Button onClick={close} disabled={loading}>取消</Button>
          <Button type="primary" loading={loading} onClick={deploy}>校验并部署</Button>
        </Space>
      }
      maskClosable={false}
      destroyOnClose
    >
      <Form form={form} layout="vertical" initialValues={{ seed: false }}>
        <Space align="end" wrap style={{ width: "100%" }}>
          <Form.Item name="biz_name" label="系统名称" style={{ marginBottom: 8, minWidth: 200 }}
                     rules={[{ required: true, message: "请填写系统名称" }]}>
            <Input placeholder="给这套系统起个名" maxLength={24} />
          </Form.Item>
          <Form.Item name="description" label="系统用途" style={{ marginBottom: 8, minWidth: 260, flex: 1 }}>
            <Input placeholder="一句话说明这套系统做什么（可留空）" />
          </Form.Item>
          <Form.Item label="SQL 方言" style={{ marginBottom: 8 }}>
            <Select
              value={dialect}
              style={{ width: 150 }}
              options={DIALECT_OPTIONS}
              onChange={onDialectChange}
              disabled={!!targetConnId}
            />
          </Form.Item>
          <Form.Item label="落库位置" style={{ marginBottom: 8 }}>
            <Select
              allowClear
              placeholder="本机 SQLite（默认）"
              value={targetConnId}
              style={{ width: 220 }}
              onChange={onTargetChange}
              options={conns
                .filter((c) => c.dialect !== "sqlite")
                .map((c) => ({ value: c.id, label: `${c.name}（${c.dialect}）` }))}
            />
          </Form.Item>
          <Form.Item name="seed" valuePropName="checked" style={{ marginBottom: 8 }}>
            <Checkbox>带演示数据</Checkbox>
          </Form.Item>
        </Space>
      </Form>

      {!wide && (
        <Segmented
          block
          value={pane}
          onChange={(v) => setPane(v as "sql" | "visual")}
          style={{ marginBottom: 12 }}
          options={[
            { label: "SQL 形态", value: "sql" },
            { label: "可视化形态", value: "visual" },
          ]}
        />
      )}

      {issues.length > 0 && (
        <Alert
          type="error"
          showIcon
          style={{ marginBottom: 12 }}
          message="校验未通过，请按定位修正"
          description={
            <ul style={{ margin: 0, paddingLeft: 18 }}>
              {issues.map((e, i) => (
                <li key={i}>
                  {e.table ? `【${e.table}${e.column ? `.${e.column}` : ""}】` : ""}{e.message}
                </li>
              ))}
            </ul>
          }
        />
      )}

      {draft.tables.length > 0 && (
        <Space style={{ marginBottom: 8 }} size={8} wrap>
          <Tag color="blue">{draft.tables.length} 张表</Tag>
          <Text type="secondary" style={{ fontSize: 12 }}>
            归属列与最终页面由系统在落库时生成，无需手写
          </Text>
        </Space>
      )}

      <div style={{ display: "flex", gap: 16, alignItems: "flex-start" }}>
        {sqlPane}
        {visualPane}
      </div>
    </MaximizableModal>
  );
}
